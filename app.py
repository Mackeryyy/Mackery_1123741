        ["Inspection Field", "Inspection Result"],
        ["Image Name", result["name"]],
        ["Inspection Date", result["time"]],
        ["Product Category", "Bottle"],
        ["Detection Model", "PatchCore"],
        ["Backbone", "Wide ResNet-50-2"],
        ["Processing Device", "CPU"],
        ["Anomaly Score", f'{result["score"]:.4f}'],
        ["Classification", classification]
