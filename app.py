def save_history(results):

    file_exists = (
        HISTORY_FILE.exists()
        and HISTORY_FILE.stat().st_size > 0
    )

    with open(
        HISTORY_FILE,
        "a",
        newline="",
        encoding="utf-8"
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=HISTORY_COLUMNS
        )

        if not file_exists:
            writer.writeheader()

        for result in results:

            writer.writerow({
                "Date and Time": result["time"],
                "Image Name": result["name"],
                "Classification": (
                    "Anomaly"
                    if result["label"] == 1
                    else "Normal"
                ),
                "Anomaly Score": f'{result["score"]:.4f}'
            })


def read_history():

    if not HISTORY_FILE.exists():
        return []

    with open(
        HISTORY_FILE,
        "r",
        newline="",
        encoding="utf-8"
    ) as file:

        return list(csv.DictReader(file))


