def create_mask(pred_mask):

    mask = np.squeeze(pred_mask)

    mask = (mask > 0).astype(np.uint8) * 255

    buffer = BytesIO()

    Image.fromarray(mask).save(
        buffer,
        format="PNG"
    )

    buffer.seek(0)

    return buffer.getvalue()


def create_grayscale_anomaly_map(anomaly_map, output_size=None):

    anomaly_map = np.asarray(anomaly_map, dtype=np.float32)
    anomaly_map = np.nan_to_num(anomaly_map)

    min_value = float(anomaly_map.min())
    max_value = float(anomaly_map.max())

    if max_value > min_value:
        normalized = (
            (anomaly_map - min_value)
            / (max_value - min_value)
        )
    else:
        normalized = np.zeros_like(anomaly_map)

    grayscale = (normalized * 255).astype(np.uint8)
    result = Image.fromarray(grayscale, mode="L")

    if output_size is not None:
        result = result.resize(
            output_size,
            Image.Resampling.BILINEAR
        )

    buffer = BytesIO()
    result.save(buffer, format="PNG")
    buffer.seek(0)

    return buffer.getvalue()


def create_detection_outline(original_image, pred_mask):

    if pred_mask is None:
        return None

    original = original_image.convert("RGBA")

    mask_array = np.asarray(pred_mask).squeeze()
    mask_array = np.nan_to_num(mask_array)
    binary_mask = (mask_array > 0).astype(np.uint8) * 255

    mask_image = Image.fromarray(binary_mask, mode="L")
    mask_image = mask_image.resize(
        original.size,
        Image.Resampling.NEAREST
    )

    # The difference between dilation and erosion produces
    # an outline around the predicted defect region.
    dilated = mask_image.filter(ImageFilter.MaxFilter(5))
    eroded = mask_image.filter(ImageFilter.MinFilter(5))
    outline = ImageChops.subtract(dilated, eroded)

    red_layer = Image.new(
        "RGBA",
        original.size,
        (230, 35, 35, 0)
    )
    red_layer.putalpha(outline)

    final_image = Image.alpha_composite(original, red_layer)

    buffer = BytesIO()
    final_image.convert("RGB").save(buffer, format="PNG")
    buffer.seek(0)

    return buffer.getvalue()


